#!/usr/bin/env python3
"""Mechanically generate the ESPHome component from this project's C core.

Run after edits to core/. Never copy app_main or native partitions.
"""
from pathlib import Path
import re

root = Path(__file__).resolve().parent
native = root / "core"
target = root / "components" / "tygbot"
for name in ("core.c", "auth.c", "protocol.c", "web.c", "sip.c", "talk.c", "core.h", "auth.h", "tyg.h"):
    text = (native / name).read_text()
    if name.endswith(".h"):
        text = text.replace("#pragma once", '#pragma once\n#ifdef __cplusplus\nextern "C" {\n#endif', 1)
        text += '\n#ifdef __cplusplus\n}\n#endif\n'
    if name == "web.c":
        begin = text.index('extern const unsigned char index_start[]')
        # Stop at the first project definition (not typedef), preserving stack/version macros.
        end = text.index('#define TG_SSE_STACK_BYTES', begin)
        declarations = ''.join(f'extern const unsigned char {symbol}_start[];\nextern const unsigned int {symbol}_size;\n' for symbol in ("index", "auth", "icon", "events", "setup"))
        text = text[:begin] + declarations + text[end:]
        for symbol in ("index", "auth", "icon", "events", "setup"):
            text = text.replace(f'{symbol}_end-{symbol}_start', f'{symbol}_size')
    (target / name).write_text("/* GENERATED by sync_core.py; edit ../../core/ instead. */\n" + text)
parts = ["/* GENERATED embedded original web UI; no credentials. */"]
for filename, symbol in (("index.html", "index"), ("login.html", "auth"), ("icon.png", "icon"), ("events.js", "events"), ("setup.html", "setup")):
    data = (native / filename).read_bytes()
    lines = [", ".join(str(x) for x in data[i:i+24]) for i in range(0, len(data), 24)]
    parts.append(f'const unsigned char {symbol}_start[] = {{\n' + ',\n'.join(lines) + '\n};\n' + f'const unsigned int {symbol}_size = {len(data)};')
(target / "assets.c").write_text('\n'.join(parts) + '\n')
print("Vendored C core and assets; app_main / Wi-Fi / partitions deliberately excluded.")
